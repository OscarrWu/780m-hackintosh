#!/usr/bin/env python3
"""gen_census.py - emit src/dcn314/dcn314_census.tsv: the stage-1 survey read census (D6/D7/D8).

  python3 src/dcn314/gen/gen_census.py            rewrite the TSV
  python3 src/dcn314/gen/gen_census.py --check    fail if the TSV is stale

dcn314 sibling of tools/dcn41/gen_census.py (kept unchanged). It reads the generated dcn314_regs.h so
the census can only ever list offsets the generator actually emitted (no hand-typed addresses). The
absolute column uses the same PLACEHOLDER segment bases as the allowlist and is tagged TODO(survey).
"""
import re
import sys

import dcn314lib as L

OUT = L.SRC / "dcn314_census.tsv"
REGS_H = L.SRC / "dcn314_regs.h"

PURPOSE = {
    "OTG": "OTG timing / scanout position / frame_count / sync status (D6,D8)",
    "HUBP": "HUBP plane surface address / format / tiling / viewport (D6)",
    "HUBPREQ": "HUBPREQ plane surface address / format / tiling / in-use (D6)",
    "AUX": "AUX request/status registers for the minimal read transaction (D6)",
    "DIG": "DIG front/back-end enable and clock status (D7)",
    "DP": "DP link status / embedded-panel / FEC status (D7)",
    "DIO": "DIO link encoder type (D7)",
    "PWRSEQ": "DIO PWM brightness / period / reference divider (D7)",
}

ROW = re.compile(r'^/\* ((?:reg\w+ 0x[0-9a-f]+(?:, )?)+); BASE_IDX (\d) \*/$')


def group_of(regname):
    stem = regname[3:].split("_")[0]
    for g in ("HUBPREQ", "HUBP", "PWRSEQ", "OTG", "AUX", "DIG", "DP", "DIO"):
        if stem.startswith(g):
            return g
    return stem


def generate():
    if not REGS_H.exists():
        raise SystemExit(f"gen_census: {REGS_H} missing - run gen_regs.py first")
    rows = []
    for line in REGS_H.read_text().splitlines():
        m = ROW.match(line)
        if not m:
            continue
        b = int(m.group(2))
        for rm in re.finditer(r'(reg\w+) (0x[0-9a-f]+)', m.group(1)):
            name, off = rm.group(1), int(rm.group(2), 16)
            g = group_of(name)
            rows.append((L.PLACEHOLDER_SEGS[b] + off, b, off, name, g,
                         PURPOSE.get(g, "survey readout")))
    rows.sort()
    out = [
        f"# dcn314_census.tsv - GENERATED by src/dcn314/gen/gen_census.py; do not edit (regenerate, then --check).",
        f"# Source: Linux {L.LINUX_VERSION} dcn_3_1_4_offset.h via dcn314_regs.h. abs_placeholder = "
        f"PLACEHOLDER seg[BASE_IDX] + offset; TODO(survey 回填) - NOT this part's address space.",
        "abs_placeholder\tbase_idx\toffset\tregister\tgroup\tpurpose",
    ]
    for a, b, off, name, g, why in rows:
        out.append(f"0x{a:08x}\t{b}\t0x{off:04x}\t{name}\t{g}\t{why}")
    return "\n".join(out) + "\n", len(rows)


def main():
    text, n = generate()
    if "--check" in sys.argv:
        cur = OUT.read_text() if OUT.exists() else ""
        if cur != text:
            raise SystemExit(f"gen_census --check: {OUT} is STALE (regenerate)")
        print(f"gen_census --check: OK - {n} rows")
        return 0
    OUT.write_text(text)
    print(f"gen_census: wrote {OUT} ({n} rows)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
